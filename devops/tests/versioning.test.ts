function WriteWorkspaceFile(Root: string, RelativePath: string, Content: string): void {
  const FilePath = Path.join(Root, RelativePath)
  Fs.mkdirSync(Path.dirname(FilePath), { recursive: true })
  Fs.writeFileSync(FilePath, Content)
}

function CreateWorkspace(ManifestVersion = '0.0.0', LockVersion = '0.0.0'): Workspace {
  const Root = Fs.mkdtempSync(Path.join(Os.tmpdir(), 'oxibelt-versioning-'))
  const ManifestPath = Path.join(Root, 'Cargo.toml')
  const LockfilePath = Path.join(Root, 'Cargo.lock')
  const RootCargoPackages = RepositoryVersionPolicy.cargoPackages.filter(
    Package => Package.lockfilePath === RepositoryVersionPolicy.lockfilePath
  )

  WriteWorkspaceFile(
    Root,
    RepositoryVersionPolicy.manifestPath,
    `[workspace]
members = [
${RootCargoPackages.map(Package => `  "${Path.posix.dirname(Package.manifestPath)}",`).join('\n')}
]

[workspace.package]
version = "${ManifestVersion}"
edition = "2024"
rust-version = "1.97"
license = "Apache-2.0"
publish = false
`
  )

  for (const Package of RepositoryVersionPolicy.cargoPackages) {
    const VersionField = Package.versionSource === 'workspace'
      ? 'version.workspace = true'
      : `version = "${ManifestVersion}"`
    WriteWorkspaceFile(
      Root,
      Package.manifestPath,
      `[package]
name = "${Package.name}"
${VersionField}
`
    )
  }

  const Lockfiles = new Map<
    string,
    Array<(typeof RepositoryVersionPolicy.cargoPackages)[number]>
  >()
  for (const Package of RepositoryVersionPolicy.cargoPackages) {
    const Packages = Lockfiles.get(Package.lockfilePath) ?? []
    Packages.push(Package)
    Lockfiles.set(Package.lockfilePath, Packages)
  }
  for (const [LockPath, Packages] of Lockfiles) {
    WriteWorkspaceFile(
      Root,
      LockPath,
      `# This file is automatically @generated by Cargo.
version = 4

${Packages.map(Package => `[[package]]
name = "${Package.name}"
version = "${LockVersion}"
`).join('\n')}

[[package]]
name = "serde"
version = "1.0.228"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "placeholder"
`
    )
  }

  WriteWorkspaceFile(
    Root,
    'package.json',
    `${JSON.stringify({
      name: 'oxibelt',
      private: true,
      workspaces: ['devops', 'ui/*']
    }, null, 2)}\n`
  )
  WriteWorkspaceFile(
    Root,
    RepositoryVersionPolicy.pnpmWorkspacePath,
    `packages:
${RepositoryVersionPolicy.npmWorkspacePatterns.map(Pattern => `  - "${Pattern}"`).join('\n')}
`
  )
  WriteWorkspaceFile(
    Root,
    'devops/package.json',
    `${JSON.stringify({
      name: '@oxibelt/devops',
      version: RepositoryVersionPolicy.committedVersion,
      private: true,
      type: 'module'
    }, null, 2)}\n`
  )
  WriteWorkspaceFile(
    Root,
    'ui/person-proof/package.json',
    `${JSON.stringify({
      name: '@oxibelt/person-proof-ui',
      version: RepositoryVersionPolicy.committedVersion,
      private: true,
      type: 'module'
    }, null, 2)}\n`
  )

  for (const ChartPath of RepositoryVersionPolicy.helmCharts) {
    WriteWorkspaceFile(
      Root,
      ChartPath,
      `apiVersion: v2
name: fixture
version: ${RepositoryVersionPolicy.committedVersion}
appVersion: "${RepositoryVersionPolicy.committedVersion}"
`
    )
  }

  WriteWorkspaceFile(
    Root,
    RepositoryVersionPolicy.dockerfilePath,
    `ARG OXIBELT_BUILD_VERSION=${RepositoryVersionPolicy.archiveIdentity.version}
ARG OXIBELT_BUILD_REVISION=${RepositoryVersionPolicy.archiveIdentity.revision}
ARG OXIBELT_BUILD_REF=${RepositoryVersionPolicy.archiveIdentity.ref}
ARG OXIBELT_BUILD_DIRTY=${RepositoryVersionPolicy.archiveIdentity.dirty}
ARG OXIBELT_BUILD_KIND=${RepositoryVersionPolicy.archiveIdentity.kind}
ARG OXIBELT_REF_NAME=${RepositoryVersionPolicy.archiveIdentity.version}

FROM scratch
`
  )
  WriteWorkspaceFile(
    Root,
    RepositoryVersionPolicy.releaseHelperPath,
    `derived_revision=""
derived_dirty="${RepositoryVersionPolicy.archiveIdentity.dirty}"
derived_kind="${RepositoryVersionPolicy.archiveIdentity.kind}"
derived_ref="${RepositoryVersionPolicy.archiveIdentity.ref}"
derived_version="${RepositoryVersionPolicy.archiveIdentity.version}"
if [[ "\${derived_revision}" =~ ^[0-9a-f]{40}$ ]]; then
  derived_dirty="clean"
  derived_dirty="dirty"
  derived_ref="$(git -C "\${repo_root}" symbolic-ref -q HEAD 2>/dev/null || true)"
  derived_kind="tagged_development"
  derived_ref="refs/tags/\${release_tag}"
  derived_version="\${release_tag}"
  derived_kind="git_development"
  derived_version="0.0.0-dev.g\${derived_revision:0:8}"
  derived_version="\${derived_version}+dirty"
fi
oxibelt_version="\${OXIBELT_DOCKER_IMAGE_VERSION:-\${derived_version}}"
oxibelt_revision="\${OXIBELT_DOCKER_IMAGE_REVISION:-\${derived_revision:-unknown}}"
oxibelt_source_ref="\${OXIBELT_DOCKER_IMAGE_SOURCE_REF:-\${derived_ref}}"
oxibelt_source_dirty="\${OXIBELT_DOCKER_IMAGE_SOURCE_DIRTY:-\${derived_dirty}}"
oxibelt_build_kind="\${OXIBELT_DOCKER_IMAGE_BUILD_KIND:-\${derived_kind}}"
oxibelt_ref_name="\${OXIBELT_DOCKER_IMAGE_REF_NAME:-\${oxibelt_version}}"
case "\${artifact_arch}" in
esac
if [[ -z "\${oxibelt_revision}" ]]; then
  oxibelt_revision="unknown"
fi
`
  )
  WriteWorkspaceFile(
    Root,
    RepositoryVersionPolicy.archiveIdentitySourcePath,
    `${Array.from(
      { length: RepositoryVersionPolicy.archiveVersionLiteralOccurrences },
      () => JSON.stringify(RepositoryVersionPolicy.archiveIdentity.version)
    ).join('\n')}\n`
  )

  return { root: Root, manifestPath: ManifestPath, lockfilePath: LockfilePath }
}

function Cleanup(WorkspaceValue: Workspace): void {
  Fs.rmSync(WorkspaceValue.root, { force: true, recursive: true })
}

function ReplaceWorkspaceText(
  WorkspaceValue: Workspace,
  RelativePath: string,
  Search: string,
  Replacement: string
): void {
  const FilePath = Path.join(WorkspaceValue.root, RelativePath)
  const Content = Fs.readFileSync(FilePath, 'utf8')
  const Next = Content.replace(Search, Replacement)
  if (Next === Content) {
    throw new Error(`fixture replacement did not match ${RelativePath}: ${Search}`)
  }
  Fs.writeFileSync(FilePath, Next)
}

function PolicyFilePaths(): string[] {
  return [...new Set([
    RepositoryVersionPolicy.manifestPath,
    RepositoryVersionPolicy.lockfilePath,
    ...RepositoryVersionPolicy.cargoPackages.flatMap(Package => [
      Package.manifestPath,
      Package.lockfilePath
    ]),
    ...RepositoryVersionPolicy.npmPackages.map(Package => Package.packagePath),
    RepositoryVersionPolicy.pnpmWorkspacePath,
    ...RepositoryVersionPolicy.helmCharts,
    RepositoryVersionPolicy.dockerfilePath,
    RepositoryVersionPolicy.releaseHelperPath,
    RepositoryVersionPolicy.archiveIdentitySourcePath
  ])].sort()
}

function SnapshotPolicyFiles(WorkspaceValue: Workspace): Map<string, string> {
  return new Map(PolicyFilePaths().map(RelativePath => [
    RelativePath,
    Fs.readFileSync(Path.join(WorkspaceValue.root, RelativePath), 'utf8')
  ]))
}

function LockPackageVersion(Content: string, PackageNameValue: string): string {
  const EscapedName = PackageNameValue.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const Match = new RegExp(
    `\\[\\[package\\]\\]\\s+name = "${EscapedName}"\\s+version = "([^"]+)"`,
    'm'
  ).exec(Content)
  if (Match === null) {
    throw new Error(`lock fixture is missing ${PackageNameValue}`)
  }
  return Match[1]
}

function AssertRepresentativeManifestArchs(
  Plan: ReturnType<typeof BuildImageReleasePlan>,
  Role: 'standalone' | 'dataplane' | 'dataplane-strict' | 'controller' | 'tools' | 'keysigner' = 'standalone'
): void {
  const ExpectedArchs = ['amd64', 'arm64', 'riscv64']
  const ReleaseManifest = Plan.manifests.find(Manifest => Manifest.role === Role && Manifest.name === 'release')
  const AlpineMuslManifest = Plan.manifests.find(
    Manifest => Manifest.role === Role && Manifest.name === 'alpine-musl'
  )
  const Amd64 = Plan.artifacts.find(Artifact => Artifact.role === Role && Artifact.artifactArch === 'amd64')

  if (ReleaseManifest === undefined || AlpineMuslManifest === undefined) {
    throw new Error('image plan should include representative release and alpine-musl manifests')
  }
  if (Amd64 === undefined) {
    throw new Error('image plan should include the amd64 artifact')
  }

  Assert.deepEqual(ReleaseManifest.artifactArchs, ExpectedArchs)
  Assert.deepEqual(AlpineMuslManifest.artifactArchs, ExpectedArchs)
  Assert.equal(ReleaseManifest.artifactArchs.includes('amd64v2'), false)
  Assert.equal(AlpineMuslManifest.artifactArchs.includes('amd64v2'), false)
  Assert.equal(Amd64.platform, 'linux/amd64')
  Assert.equal(Amd64.dockerArchitecture, 'amd64')
  Assert.equal(Amd64.targetCpu, 'x86-64-v3')
}

