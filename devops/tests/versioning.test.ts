test('release mode rewrites Cargo versions and emits the image plan', TestContext => {
  const WorkspaceValue = CreateWorkspace()
  const ImagePlanOutput = Path.join(WorkspaceValue.root, 'image-plan.json')
  const Before = SnapshotPolicyFiles(WorkspaceValue)
  TestContext.after(() => Cleanup(WorkspaceValue))

  const Result = RunVersioning({
    workspacePath: WorkspaceValue.root,
    manifestPath: 'Cargo.toml',
    lockfilePath: 'Cargo.lock',
    packageName: PackageName,
    ref: 'refs/tags/1.5.0-beta.1',
    revision: 'aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa',
    eventName: 'release',
    releasePrerelease: true,
    releasePublish: true,
    imagePlanOutput: ImagePlanOutput
  })

  const Manifest = Fs.readFileSync(WorkspaceValue.manifestPath, 'utf8')
  const Plan = JSON.parse(Fs.readFileSync(ImagePlanOutput, 'utf8')) as ReleasePlanSummary

  Assert.deepEqual(Result, {
    mode: 'release',
    packageName: PackageName,
    version: '1.5.0-beta.1'
  })
  Assert.match(Manifest, /^version = "1\.5\.0-beta\.1"$/m)
  Assert.match(Manifest, /^publish = false$/m)
  for (const Package of RepositoryVersionPolicy.cargoPackages) {
    const Expected = Package.releaseRewrite ? '1.5.0-beta.1' : RepositoryVersionPolicy.committedVersion
    Assert.equal(LockPackageVersion(
      Fs.readFileSync(Path.join(WorkspaceValue.root, Package.lockfilePath), 'utf8'),
      Package.name
    ), Expected)
  }
  for (const [RelativePath, Content] of Before) {
    if (
      RelativePath !== RepositoryVersionPolicy.manifestPath &&
      RelativePath !== RepositoryVersionPolicy.lockfilePath
    ) {
      Assert.equal(
        Fs.readFileSync(Path.join(WorkspaceValue.root, RelativePath), 'utf8'),
        Content,
        `release mode should not rewrite ${RelativePath}`
      )
    }
  }
  Assert.equal(Plan.tag, '1.5.0-beta.1')
  Assert.equal(Plan.kind, 'beta')
})

