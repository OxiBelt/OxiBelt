const UPSTREAM_SCHEME_ANNOTATION: &str = "oxibelt.dev/upstream-scheme";
const GATEWAY_GROUP: &str = "gateway.networking.k8s.io";
const GENERATED_HEADER: &str = "# Generated by oxibelt-gateway-controller. Do not edit.\n\
# This file is controller-owned and is intended to be included from the base OxiBelt config.\n\n";

#[derive(Debug, Clone)]
pub struct RenderedConfig {
  pub toml: String,
  pub diagnostics: Vec<Diagnostic>,
}

#[derive(Debug, Clone)]
struct ServiceInfo {
  namespace: String,
  name: String,
  ports: Vec<ServicePort>,
  scheme: String,
}

#[derive(Debug, Clone)]
struct ServicePort {
  name: Option<String>,
  port: u16,
}

#[derive(Debug, Clone)]
struct GatewayInfo {
  namespace: String,
  name: String,
  listeners: Vec<ListenerInfo>,
}

#[derive(Debug, Clone)]
struct ListenerInfo {
  name: Option<String>,
  protocol: String,
  hostname: Option<String>,
  tls_mode: Option<String>,
}

#[derive(Debug, Clone)]
struct ReferenceGrantInfo {
  namespace: String,
  from_namespaces: HashSet<String>,
  from_kinds: HashSet<String>,
  to_kinds: HashSet<String>,
}

#[derive(Debug, Clone)]
struct GeneratedRoute {
  source: String,
  name: String,
  hosts: Vec<String>,
  path_prefix: String,
  path_exact: Option<String>,
  methods: Vec<String>,
  headers: Vec<NamedExactMatch>,
  queries: Vec<NamedExactMatch>,
  priority: i32,
  upstream_pool: Option<String>,
  rewrite: Option<RewriteAction>,
  redirect: Option<RedirectAction>,
}

#[derive(Debug, Clone)]
struct GeneratedPool {
  source: String,
  name: String,
  servers: Vec<GeneratedServer>,
}

#[derive(Debug, Clone)]
struct GeneratedServer {
  id: String,
  origin: String,
  weight: u32,
}

#[derive(Debug, Clone)]
struct GeneratedSniRule {
  source: String,
  name: String,
  server_names: Vec<String>,
  target: String,
}

#[derive(Debug, Clone)]
struct NamedExactMatch {
  name: String,
  value: String,
}

#[derive(Debug, Clone)]
struct RewriteAction {
  path: Option<String>,
  query: Option<String>,
}

#[derive(Debug, Clone)]
struct RedirectAction {
  status: u16,
  location_template: String,
}

#[derive(Default)]
struct TranslationState {
  services: HashMap<ObjectKey, ServiceInfo>,
  gateway_classes: HashSet<String>,
  gateways: HashMap<ObjectKey, GatewayInfo>,
  reference_grants: Vec<ReferenceGrantInfo>,
  pools: BTreeMap<String, GeneratedPool>,
  routes: Vec<GeneratedRoute>,
  sni_rules: Vec<GeneratedSniRule>,
  diagnostics: Vec<Diagnostic>,
}

pub fn translate_objects(
  objects: &[KubernetesObject],
  args: &SharedArgs,
) -> anyhow::Result<RenderedConfig> {
  let mut state = TranslationState::default();
  state.index_supporting_objects(objects, args)?;
  for object in objects {
    match object.kind.as_str() {
      "HTTPRoute" => state.translate_http_route(object),
      "TLSRoute" => state.translate_tls_route(object),
      "TCPRoute" => state.diagnostics.push(Diagnostic::warning(
        model_object_ref(object),
        "TCPRoute is status-only and unsupported in OxiBelt Gateway API controller v1",
      )),
      _ => {}
    }
  }
  Ok(RenderedConfig {
    toml: render_toml(&state, args),
    diagnostics: state.diagnostics,
  })
}

impl TranslationState {
  fn index_supporting_objects(
    &mut self,
    objects: &[KubernetesObject],
    args: &SharedArgs,
  ) -> anyhow::Result<()> {
    for object in objects {
      match object.kind.as_str() {
        "Service" => {
          let service = parse_service(object)?;
          self.services.insert(object.key(), service);
        }
        "GatewayClass" => {
          if string_at(&object.spec, &["controllerName"]) == Some(args.controller_name.as_str()) {
            self.gateway_classes.insert(object.name().to_string());
          }
        }
        "Gateway" => {
          if let Some(gateway) = parse_gateway(object, &self.gateway_classes) {
            self.gateways.insert(object.key(), gateway);
          }
        }
        "ReferenceGrant" => {
          if let Some(grant) = parse_reference_grant(object) {
            self.reference_grants.push(grant);
          }
        }
        _ => {}
      }
    }
    Ok(())
  }

  fn translate_tls_route(&mut self, route: &KubernetesObject) {
    let attachments = self.attachments_for(route, &["TLS"]);
    if attachments.is_empty() {
      self.diagnostics.push(Diagnostic::warning(
        model_object_ref(route),
        "route is not attached to an in-scope TLS Gateway listener",
      ));
      return;
    }

    let route_hosts = string_array_at(&route.spec, &["hostnames"]);
    let rules = route.spec.get("rules").and_then(Value::as_array);
    let Some(rules) = rules else {
      self.diagnostics.push(Diagnostic::error(
        model_object_ref(route),
        "TLSRoute spec.rules is required",
      ));
      return;
    };

    for attachment in attachments {
      if attachment.listener.tls_mode.as_deref() != Some("Passthrough") {
        self.diagnostics.push(Diagnostic::error(
          model_object_ref(route),
          "TLSRoute requires a Gateway TLS listener with tls.mode = Passthrough",
        ));
        continue;
      }
      let hosts = intersect_hosts(&route_hosts, attachment.listener.hostname.as_deref());
      for (rule_index, rule) in rules.iter().enumerate() {
        let source = format!(
          "TLSRoute/{}/{} rule {} via Gateway/{}/{}",
          route.namespace(),
          route.name(),
          rule_index,
          attachment.gateway.namespace,
          attachment.gateway.name,
        );
        let Some(target) =
          self.tls_target(route, rule.get("backendRefs").and_then(Value::as_array))
        else {
          continue;
        };
        self.sni_rules.push(GeneratedSniRule {
          source,
          name: sanitize_name(&format!(
            "gwapi-tls-{}-{}-{}",
            route.namespace(),
            route.name(),
            rule_index
          )),
          server_names: if hosts.is_empty() {
            vec!["*".to_string()]
          } else {
            hosts.clone()
          },
          target,
        });
      }
    }
  }

  fn tls_target(
    &mut self,
    route: &KubernetesObject,
    backend_refs: Option<&Vec<Value>>,
  ) -> Option<String> {
    let Some(backend_refs) = backend_refs else {
      self.diagnostics.push(Diagnostic::error(
        model_object_ref(route),
        "TLSRoute rule.backendRefs is required",
      ));
      return None;
    };
    let nonzero = backend_refs
      .iter()
      .filter(|backend| u32_at(backend, &["weight"]).unwrap_or(1) > 0)
      .collect::<Vec<_>>();
    if nonzero.len() != 1 {
      self.diagnostics.push(Diagnostic::error(
        model_object_ref(route),
        "TLSRoute v1 supports exactly one nonzero Service backendRef",
      ));
      return None;
    }
    let backend = nonzero[0];
    if !backend_ref_is_service(backend) {
      self.diagnostics.push(Diagnostic::error(
        model_object_ref(route),
        "TLSRoute only supports Kubernetes Service backendRefs",
      ));
      return None;
    }
    let name = string_at(backend, &["name"])?;
    let namespace = string_at(backend, &["namespace"]).unwrap_or(route.namespace());
    if namespace != route.namespace() && !self.reference_allowed(route, "TLSRoute", namespace) {
      self.diagnostics.push(Diagnostic::error(
        model_object_ref(route),
        format!("cross-namespace backendRef to {namespace}/{name} requires ReferenceGrant"),
      ));
      return None;
    }
    let key = ObjectKey {
      namespace: namespace.to_string(),
      name: name.to_string(),
    };
    let Some(service) = self.services.get(&key) else {
      self.diagnostics.push(Diagnostic::error(
        model_object_ref(route),
        format!("backend Service {namespace}/{name} was not found in input snapshot"),
      ));
      return None;
    };
    let Some(port) = backend_port(backend, service) else {
      self.diagnostics.push(Diagnostic::error(
        model_object_ref(route),
        format!("backend Service {namespace}/{name} does not expose the referenced port"),
      ));
      return None;
    };
    Some(format!(
      "{}.{}.svc.cluster.local:{}",
      service.name, service.namespace, port
    ))
  }

  fn reference_allowed(
    &self,
    route: &KubernetesObject,
    from_kind: &str,
    target_namespace: &str,
  ) -> bool {
    self.reference_grants.iter().any(|grant| {
      grant.namespace == target_namespace
        && grant.from_namespaces.contains(route.namespace())
        && grant.from_kinds.contains(from_kind)
        && grant.to_kinds.contains("Service")
    })
  }

  fn attachments_for(&self, route: &KubernetesObject, protocols: &[&str]) -> Vec<RouteAttachment> {
    let mut attachments = Vec::new();
    let parent_refs = route
      .spec
      .get("parentRefs")
      .and_then(Value::as_array)
      .cloned()
      .unwrap_or_default();
    for parent in parent_refs {
      if !parent_ref_is_gateway(&parent) {
        continue;
      }
      let Some(parent_name) = string_at(&parent, &["name"]) else {
        continue;
      };
      let parent_namespace = string_at(&parent, &["namespace"]).unwrap_or(route.namespace());
      let key = ObjectKey {
        namespace: parent_namespace.to_string(),
        name: parent_name.to_string(),
      };
      let Some(gateway) = self.gateways.get(&key) else {
        continue;
      };
      let section_name = string_at(&parent, &["sectionName"]);
      for listener in &gateway.listeners {
        if !protocols
          .iter()
          .any(|protocol| *protocol == listener.protocol)
        {
          continue;
        }
        if section_name.is_some() && listener.name.as_deref() != section_name {
          continue;
        }
        attachments.push(RouteAttachment {
          gateway: gateway.clone(),
          listener: listener.clone(),
        });
      }
    }
    attachments
  }
}

#[derive(Debug, Clone)]
struct RouteAttachment {
  gateway: GatewayInfo,
  listener: ListenerInfo,
}

fn parse_service(object: &KubernetesObject) -> anyhow::Result<ServiceInfo> {
  let mut ports = Vec::new();
  for port in object
    .spec
    .get("ports")
    .and_then(Value::as_array)
    .cloned()
    .unwrap_or_default()
  {
    let Some(number) = u16_at(&port, &["port"]) else {
      continue;
    };
    ports.push(ServicePort {
      name: string_at(&port, &["name"]).map(str::to_string),
      port: number,
    });
  }
  let scheme = object
    .metadata
    .annotations
    .get(UPSTREAM_SCHEME_ANNOTATION)
    .map(String::as_str)
    .unwrap_or("http");
  if !matches!(scheme, "http" | "https") {
    bail!(
      "Service/{}/{} annotation {UPSTREAM_SCHEME_ANNOTATION} must be http or https",
      object.namespace(),
      object.name()
    );
  }
  Ok(ServiceInfo {
    namespace: object.namespace().to_string(),
    name: object.name().to_string(),
    ports,
    scheme: scheme.to_string(),
  })
}

fn parse_gateway(
  object: &KubernetesObject,
  accepted_classes: &HashSet<String>,
) -> Option<GatewayInfo> {
  let class = string_at(&object.spec, &["gatewayClassName"])?;
  if !accepted_classes.contains(class) {
    return None;
  }
  let listeners = object
    .spec
    .get("listeners")
    .and_then(Value::as_array)
    .cloned()
    .unwrap_or_default()
    .into_iter()
    .filter_map(|listener| {
      let protocol = string_at(&listener, &["protocol"])?.to_string();
      let _port = u16_at(&listener, &["port"])?;
      Some(ListenerInfo {
        name: string_at(&listener, &["name"]).map(str::to_string),
        protocol,
        hostname: string_at(&listener, &["hostname"]).map(str::to_string),
        tls_mode: string_at(&listener, &["tls", "mode"]).map(str::to_string),
      })
    })
    .collect();
  Some(GatewayInfo {
    namespace: object.namespace().to_string(),
    name: object.name().to_string(),
    listeners,
  })
}

fn parse_reference_grant(object: &KubernetesObject) -> Option<ReferenceGrantInfo> {
  let mut from_namespaces = HashSet::new();
  let mut from_kinds = HashSet::new();
  for from in object.spec.get("from")?.as_array()? {
    let group = string_at(from, &["group"]).unwrap_or("");
    if group != GATEWAY_GROUP {
      continue;
    }
    if let Some(namespace) = string_at(from, &["namespace"]) {
      from_namespaces.insert(namespace.to_string());
    }
    if let Some(kind) = string_at(from, &["kind"]) {
      from_kinds.insert(kind.to_string());
    }
  }
  let mut to_kinds = HashSet::new();
  for to in object.spec.get("to")?.as_array()? {
    let group = string_at(to, &["group"]).unwrap_or("");
    if group.is_empty()
      && let Some(kind) = string_at(to, &["kind"])
    {
      to_kinds.insert(kind.to_string());
    }
  }
  Some(ReferenceGrantInfo {
    namespace: object.namespace().to_string(),
    from_namespaces,
    from_kinds,
    to_kinds,
  })
}

fn backend_ref_is_service(backend: &Value) -> bool {
  let group = string_at(backend, &["group"]).unwrap_or("");
  let kind = string_at(backend, &["kind"]).unwrap_or("Service");
  group.is_empty() && kind == "Service"
}

fn parent_ref_is_gateway(parent: &Value) -> bool {
  let group = string_at(parent, &["group"]).unwrap_or(GATEWAY_GROUP);
  let kind = string_at(parent, &["kind"]).unwrap_or("Gateway");
  group == GATEWAY_GROUP && kind == "Gateway"
}

fn backend_port(backend: &Value, service: &ServiceInfo) -> Option<u16> {
  if let Some(port) = u16_at(backend, &["port"]) {
    return service
      .ports
      .iter()
      .any(|candidate| candidate.port == port)
      .then_some(port);
  }
  if let Some(name) = string_at(backend, &["port"]) {
    return service
      .ports
      .iter()
      .find(|candidate| candidate.name.as_deref() == Some(name))
      .map(|candidate| candidate.port);
  }
  None
}

fn intersect_hosts(route_hosts: &[String], listener_hostname: Option<&str>) -> Vec<String> {
  let Some(listener) = listener_hostname else {
    return route_hosts.to_vec();
  };
  if route_hosts.is_empty() {
    return vec![listener.to_string()];
  }
  route_hosts
    .iter()
    .filter(|host| host_intersects(host, listener))
    .cloned()
    .collect()
}

fn host_intersects(route_host: &str, listener_host: &str) -> bool {
  host_matches(route_host, listener_host) || host_matches(listener_host, route_host)
}

fn host_matches(pattern: &str, host: &str) -> bool {
  let pattern = pattern.trim_end_matches('.').to_ascii_lowercase();
  let host = host.trim_end_matches('.').to_ascii_lowercase();
  if pattern == "*" {
    return true;
  }
  if let Some(suffix) = pattern.strip_prefix("*.") {
    return host.ends_with(&format!(".{suffix}")) && host != suffix;
  }
  pattern == host
}

fn render_toml(state: &TranslationState, args: &SharedArgs) -> String {
  let mut out = String::from(GENERATED_HEADER);
  out.push_str("# controller_name = ");
  out.push_str(&toml_string(&args.controller_name));
  out.push('\n');
  out.push_str("# managed_config_path = ");
  out.push_str(&toml_string(&args.managed_config_path));
  out.push_str("\n\n");

  for pool in state.pools.values() {
    out.push_str("# Source: ");
    out.push_str(&pool.source);
    out.push('\n');
    out.push_str("[[upstream_pools]]\n");
    out.push_str("name = ");
    out.push_str(&toml_string(&pool.name));
    out.push('\n');
    for server in &pool.servers {
      out.push_str("\n[[upstream_pools.servers]]\n");
      out.push_str("id = ");
      out.push_str(&toml_string(&server.id));
      out.push('\n');
      out.push_str("origin = ");
      out.push_str(&toml_string(&server.origin));
      out.push('\n');
      out.push_str("weight = ");
      out.push_str(&server.weight.to_string());
      out.push('\n');
    }
    out.push('\n');
  }

  for route in &state.routes {
    out.push_str("# Source: ");
    out.push_str(&route.source);
    out.push('\n');
    out.push_str("[[routes]]\n");
    out.push_str("name = ");
    out.push_str(&toml_string(&route.name));
    out.push('\n');
    out.push_str("hosts = ");
    out.push_str(&toml_string_array(&route.hosts));
    out.push('\n');
    out.push_str("path_prefix = ");
    out.push_str(&toml_string(&route.path_prefix));
    out.push('\n');
    if let Some(upstream_pool) = &route.upstream_pool {
      out.push_str("upstream_pool = ");
      out.push_str(&toml_string(upstream_pool));
      out.push('\n');
    }
    out.push_str("[routes.match]\n");
    out.push_str("priority = ");
    out.push_str(&route.priority.to_string());
    out.push('\n');
    if !route.methods.is_empty() {
      out.push_str("methods = ");
      out.push_str(&toml_string_array(&route.methods));
      out.push('\n');
    }
    if let Some(exact) = &route.path_exact {
      out.push_str("[routes.match.path]\n");
      out.push_str("exact = ");
      out.push_str(&toml_string(exact));
      out.push('\n');
    }
    for header in &route.headers {
      out.push_str("\n[[routes.match.headers]]\n");
      out.push_str("name = ");
      out.push_str(&toml_string(&header.name));
      out.push('\n');
      out.push_str("exact = ");
      out.push_str(&toml_string(&header.value));
      out.push('\n');
    }
    for query in &route.queries {
      out.push_str("\n[[routes.match.queries]]\n");
      out.push_str("name = ");
      out.push_str(&toml_string(&query.name));
      out.push('\n');
      out.push_str("exact = ");
      out.push_str(&toml_string(&query.value));
      out.push('\n');
    }
    if let Some(rewrite) = &route.rewrite {
      out.push_str("\n[routes.actions.rewrite]\n");
      if let Some(path) = &rewrite.path {
        out.push_str("path = ");
        out.push_str(&toml_string(path));
        out.push('\n');
      }
      if let Some(query) = &rewrite.query {
        out.push_str("query = ");
        out.push_str(&toml_string(query));
        out.push('\n');
      }
    }
    if let Some(redirect) = &route.redirect {
      out.push_str("\n[routes.actions.redirect]\n");
      out.push_str("status = ");
      out.push_str(&redirect.status.to_string());
      out.push('\n');
      out.push_str("location_template = ");
      out.push_str(&toml_string(&redirect.location_template));
      out.push('\n');
    }
    out.push('\n');
  }

  for rule in &state.sni_rules {
    out.push_str("# Source: ");
    out.push_str(&rule.source);
    out.push('\n');
    out.push_str("[[sni_forward.rules]]\n");
    out.push_str("name = ");
    out.push_str(&toml_string(&rule.name));
    out.push('\n');
    out.push_str("server_names = ");
    out.push_str(&toml_string_array(&rule.server_names));
    out.push('\n');
    out.push_str("target = ");
    out.push_str(&toml_string(&rule.target));
    out.push('\n');
    out.push_str("protocols = [\"tcp_tls\"]\n\n");
  }

  out
}

fn toml_string(value: &str) -> String {
  toml::Value::String(value.to_string()).to_string()
}

fn toml_string_array(values: &[String]) -> String {
  let mut text = String::from("[");
  for (index, value) in values.iter().enumerate() {
    if index > 0 {
      text.push_str(", ");
    }
    text.push_str(&toml_string(value));
  }
  text.push(']');
  text
}

fn sanitize_name(value: &str) -> String {
  let mut out = String::new();
  for ch in value.chars() {
    if ch.is_ascii_alphanumeric() {
      out.push(ch.to_ascii_lowercase());
    } else if matches!(ch, '-' | '_' | '.') {
      out.push(ch);
    } else {
      out.push('-');
    }
  }
  while out.contains("--") {
    out = out.replace("--", "-");
  }
  out.trim_matches('-').to_string()
}

fn string_at<'a>(value: &'a Value, path: &[&str]) -> Option<&'a str> {
  let mut current = value;
  for key in path {
    current = current.get(*key)?;
  }
  current.as_str()
}

fn string_array_at(value: &Value, path: &[&str]) -> Vec<String> {
  let mut current = value;
  for key in path {
    let Some(next) = current.get(*key) else {
      return Vec::new();
    };
    current = next;
  }
  current
    .as_array()
    .map(|items| {
      items
        .iter()
        .filter_map(Value::as_str)
        .map(str::to_string)
        .collect()
    })
    .unwrap_or_default()
}

fn u16_at(value: &Value, path: &[&str]) -> Option<u16> {
  let raw = u64_at(value, path)?;
  u16::try_from(raw).ok()
}

fn u32_at(value: &Value, path: &[&str]) -> Option<u32> {
  let raw = u64_at(value, path)?;
  u32::try_from(raw).ok()
}

fn u64_at(value: &Value, path: &[&str]) -> Option<u64> {
  let mut current = value;
  for key in path {
    current = current.get(*key)?;
  }
  current.as_u64()
}
